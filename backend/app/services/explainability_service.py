import json
from typing import Dict, Any, Optional
from sqlalchemy.orm import Session
from fastapi import HTTPException, status

from backend.app.models.screening import Screening
from backend.app.models.user import User
from backend.app.services.storage.factory import get_storage_provider
from backend.app.services.audit_service import create_audit_log


GRADE_NAMES = {
    0: "No Apparent Diabetic Retinopathy (Normal)",
    1: "Mild Non-Proliferative Diabetic Retinopathy (NPDR)",
    2: "Moderate Non-Proliferative Diabetic Retinopathy (NPDR)",
    3: "Severe Non-Proliferative Diabetic Retinopathy (NPDR)",
    4: "Proliferative Diabetic Retinopathy (PDR)",
}


def get_screening_explainability_data(
    screening_id: str,
    db: Session,
    current_user: User,
    client_ip: str = "127.0.0.1"
) -> Dict[str, Any]:
    """
    Service layer for retrieving transparent, clinically reviewable explainability visual artifacts.
    Enforces tenant isolation and records an audit log entry.
    """
    screening = db.query(Screening).filter(Screening.id == screening_id).first()
    if not screening:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Screening encounter not found.")

    # Isolation: PHC Worker cannot access screening records from another health center
    if current_user.role == "PHC_WORKER" and current_user.health_center_id:
        if screening.health_center_id != current_user.health_center_id:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Access denied: You do not have permission to access screening explainability from another health center."
            )

    if not screening.ai_analysis or not screening.ai_analysis.explainability_map:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="AI analysis has not been executed on this screening yet. Please call /analyze first."
        )

    storage = get_storage_provider()
    xai = screening.ai_analysis.explainability_map
    ana = screening.ai_analysis

    engine_name = ana.inference_engine or "MOCK_INFERENCE"
    is_mock = "MOCK" in engine_name.upper()

    if is_mock:
        explanation_label = "Simulated explanation generated by mock inference."
        disclaimer = "Simulated visual explanation generated by deterministic mock inference. Does not reflect trained model activations."
    else:
        explanation_label = "AI-generated visual explanation; requires ophthalmologist verification."
        disclaimer = "Grad-CAM++ activation map generated from trained EfficientNet convolutional feature maps. Requires ophthalmologist clinical verification."

    # Audit logging for explainability access
    create_audit_log(
        db=db,
        action="VIEW_EXPLAINABILITY",
        resource_type="ExplainabilityMap",
        resource_id=xai.id,
        user_id=current_user.id,
        user_role=current_user.role,
        status="SUCCESS",
        client_ip=client_ip,
        payload_data={
            "screening_id": screening.id,
            "patient_code": screening.patient.patient_code if screening.patient else None,
            "inference_engine": engine_name
        }
    )
    db.commit()

    orig_url = storage.get_url(screening.fundus_image.original_file_path) if screening.fundus_image else None
    enh_url = (
        storage.get_url(screening.fundus_image.enhanced_file_path)
        if screening.fundus_image and screening.fundus_image.enhanced_file_path
        else None
    )

    referable_status = "REFERABLE" if ana.is_referable else "NON_REFERABLE"
    uncertainty_status = "UNCERTAIN" if ana.is_uncertain else "CERTAIN"
    grade_label = f"Grade {ana.predicted_grade}: {GRADE_NAMES.get(ana.predicted_grade, 'Unknown')}"
    inference_time_sec = round(getattr(ana, "inference_latency_ms", 120) / 1000.0, 3)

    return {
        "screening_id": screening.id,
        "patient_anonymized_id": screening.patient.patient_code if screening.patient else None,
        "original_image_url": orig_url,
        "enhanced_image_url": enh_url,
        "heatmap_url": storage.get_url(xai.heatmap_file_path),
        "overlay_url": storage.get_url(xai.overlay_file_path),
        "predicted_grade": ana.predicted_grade,
        "grade_label": grade_label,
        "confidence": round(ana.confidence_score, 3),
        "uncertainty_status": uncertainty_status,
        "referable_status": referable_status,
        "clinical_explanation": ana.clinical_explanation,
        "recommended_action": getattr(ana, "recommended_action", None) or (
            "Refer to tele-ophthalmologist for confirmatory examination within 30 days." if ana.is_referable else
            "Follow-up eye check at Primary Health Centre in 6 to 12 months."
        ),
        "inference_engine": engine_name,
        "model_version": ana.model_version,
        "inference_time": inference_time_sec,
        "explanation_label": explanation_label,
        "disclaimer": disclaimer,
        "method": xai.method,
        "target_layer": xai.target_layer
    }
