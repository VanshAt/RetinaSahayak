from typing import List, Optional, Dict, Any
from pydantic import BaseModel


class IQAMetrics(BaseModel):
    sharpness_score: float
    illumination_score: float
    vessel_contrast_score: float


class IQAResult(BaseModel):
    iqa_status: str  # GOOD, BORDERLINE, REJECT
    is_acceptable: bool
    metrics: IQAMetrics
    issues: List[str] = []
    actionable_feedback: str


class DMERisk(BaseModel):
    level: str  # NONE, MILD, MODERATE, SEVERE
    exudates_near_macula: bool


class LesionEvidence(BaseModel):
    microaneurysms_detected: bool = False
    blot_hemorrhages_detected: bool = False
    hard_exudates_detected: bool = False
    neovascularization_detected: bool = False
    suspicious_quadrants: List[str] = []


class ExplainabilityDetail(BaseModel):
    heatmap_url: str
    overlay_url: str
    method: str = "Grad-CAM++"
    target_layer: str = "model.features.7"
    candidate_lesions: List[Dict[str, Any]] = []
    explanation_label: str = "Simulated explanation generated by mock inference."
    explanation_disclaimer: str = "Simulated explanation generated by mock inference. Does not reflect trained convolutional activations."



class MLAnalysisResponse(BaseModel):
    screening_id: str
    model_version: str
    inference_engine: str
    inference_time: float  # In seconds (e.g., 0.14s on CPU)
    quality_status: str  # GOOD, BORDERLINE, REJECT
    quality_score: float  # 0.0 to 100.0
    quality_issues: List[str] = []
    recapture_guidance: Optional[str] = None
    enhanced_image_url: Optional[str] = None
    predicted_grade: int
    grade_label: str  # E.g. "Grade 2: Moderate Non-Proliferative Diabetic Retinopathy (NPDR)"
    grade_name: str
    class_probabilities: Dict[str, float]
    confidence: float
    confidence_score: float
    uncertainty_status: str  # "CERTAIN" or "UNCERTAIN"
    uncertainty_score: float
    referable_status: str  # "REFERABLE" or "NON_REFERABLE"
    is_referable: bool
    is_uncertain: bool
    triage_urgency: str
    dme_risk: DMERisk
    lesion_evidence: LesionEvidence
    clinical_explanation: str
    recommended_action: str
    explainability: ExplainabilityDetail
    referral_id: Optional[str] = None
    referral_status: Optional[str] = None
    disclaimer: str = (
        "Presumptive AI Screening Observation. Not an autonomous medical diagnosis. "
        "Must be reviewed and verified by a licensed ophthalmologist before any clinical treatment."
    )
